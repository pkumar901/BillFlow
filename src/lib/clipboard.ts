/**
 * Copies text to the clipboard.
 *
 * Uses the async Clipboard API when it is available and permitted, then falls back to
 * a hidden textarea + `execCommand("copy")` for the cases where it is not - for example
 * non-secure origins, denied permission, or older browsers. Returns `false` when nothing
 * worked so the caller can show a helpful message.
 */
export async function copyText(text: string): Promise<boolean> {
  if (typeof navigator !== "undefined" && navigator.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      /* fall through to the legacy path */
    }
  }

  try {
    const area = document.createElement("textarea");
    area.value = text;
    area.setAttribute("readonly", "");
    area.style.position = "fixed";
    area.style.top = "0";
    area.style.left = "0";
    area.style.opacity = "0";
    document.body.appendChild(area);
    area.select();
    area.setSelectionRange(0, text.length);
    const copied = document.execCommand("copy");
    document.body.removeChild(area);
    return copied;
  } catch {
    return false;
  }
}
